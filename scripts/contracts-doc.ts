import { writeFileSync } from "node:fs";
import { z } from "zod";
import { SCOPE_INFO } from "@/lib/auth/machine";
import { HTTP_STATUS, OPERATIONS } from "@/lib/contracts/operations";

/**
 * `npm run contracts:doc`: write docs/CONTRACTS.md from the runtime contracts in
 * lib/contracts/operations.ts (the same definitions the HTTP API and MCP server
 * validate against), so the docs cannot drift from the code.
 */
const lines: string[] = [];
lines.push("# Operation contracts (HTTP API and MCP)");
lines.push("");
lines.push("Generated by `npm run contracts:doc` from `lib/contracts/operations.ts`. Do not edit by hand.");
lines.push("");
lines.push("Every operation is available two ways with identical validation and behavior:");
lines.push("");
lines.push("- **HTTP**: `POST /api/v1/<name>` with a JSON body. Authenticate with `Authorization: Bearer <machine token>` (scoped; see below) or a signed-in session. Responses are `{ ok: true, result }` or `{ ok: false, error: { code, message } }`. `GET /api/v1` returns this catalog as JSON Schema.");
lines.push("- **MCP**: tool `<name>` on the stdio server (`npm run mcp`). Read-only unless `MCP_SCOPES` grants more. Tools return `structuredContent` matching the output schema.");
lines.push("");
lines.push("**Idempotency.** Every mutation takes `idempotencyKey` (provider events use `eventId`). The first call with a key runs; retries with the same key return the stored result and never act twice, across restarts and workers. A retry while the first call is still running gets `in_progress`.");
lines.push("");
lines.push("**Pagination.** List operations return `nextCursor`; pass it back as `cursor`. `null` means the last page. Cursors are opaque.");
lines.push("");
lines.push("**Errors.**");
lines.push("");
lines.push("| code | HTTP | meaning |");
lines.push("|---|---|---|");
const meaning: Record<string, string> = { invalid_input: "input failed validation (details in message)", unauthenticated: "missing or invalid credentials", forbidden: "the caller lacks the operation's scope", not_found: "the referenced record does not exist", conflict: "the record is not in a state that allows this", in_progress: "the same idempotency key is still running; retry shortly", internal: "unexpected failure; safe to retry with the same key" };
for (const [code, status] of Object.entries(HTTP_STATUS)) lines.push(`| \`${code}\` | ${status} | ${meaning[code]} |`);
lines.push("");
lines.push("**Scopes.** Machine identities are configured in `MACHINE_IDENTITIES` (token SHA-256 only). Nothing is implied between scopes.");
lines.push("");
lines.push("| scope | grants |");
lines.push("|---|---|");
for (const [s, d] of Object.entries(SCOPE_INFO)) lines.push(`| \`${s}\` | ${d} |`);
lines.push("");
lines.push("## Operations");
lines.push("");
for (const o of OPERATIONS) {
  lines.push(`### \`${o.name}\``);
  lines.push("");
  lines.push(o.description);
  lines.push("");
  lines.push(`- Scope: \`${o.scope}\` · ${o.mutates ? "mutation" : "read-only"}${o.destructive ? " · destructive" : ""}${o.openWorld ? " · affects external systems" : ""}`);
  lines.push(`- Retry: ${o.retry}`);
  if (o.pagination) lines.push(`- Pagination: cursor (\`nextCursor\`), max limit ${o.pagination.maxLimit}`);
  if (o.errors.length) lines.push(`- Errors: ${o.errors.map((e) => `\`${e.code}\` when ${e.when}`).join("; ")}`);
  lines.push("");
  lines.push("Input schema:");
  lines.push("");
  lines.push("```json");
  lines.push(JSON.stringify(z.toJSONSchema(o.input, { io: "input" }), null, 2));
  lines.push("```");
  lines.push("");
  lines.push("Output schema:");
  lines.push("");
  lines.push("```json");
  lines.push(JSON.stringify(z.toJSONSchema(o.output), null, 2));
  lines.push("```");
  lines.push("");
}
writeFileSync("docs/CONTRACTS.md", lines.join("\n"));
console.log(`wrote docs/CONTRACTS.md (${OPERATIONS.length} operations)`);
