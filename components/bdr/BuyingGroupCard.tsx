import { ConversationPanel, type PanelContext } from "@/components/bdr/ConversationPanel";
import { ContactActions, ResearchContactsButton } from "@/components/bdr/ContactActions";
import { Badge, Card, fmtAgo } from "@/components/ui";
import { ROLE_LABEL } from "@/lib/engine/buying-group";
import type { ContactView, CoverageView } from "@/lib/engine/contact-commands";
import { isPhoneVerified } from "@/lib/engine/contact-fields";
import type { BuyingContact } from "@/lib/types";

/**
 * Contacts: the buying group as a rep works it. Who is in the group and why,
 * how sure we are of each person's role and details, where each person is
 * in outreach, which roles are still missing, and one next action.
 */

function Check({ ok, label, title }: { ok: boolean | null; label: string; title?: string }) {
  if (ok === null) return <span className="text-[11.5px] text-[var(--muted)]">no {label}</span>;
  return <Badge tone={ok ? "good" : "warn"} title={title}>{`${ok ? "✓" : "!"} ${label}`}</Badge>;
}

const STATUS_TONE: Record<BuyingContact["status"], "good" | "warn" | "bad" | "info" | "neutral"> = { selected: "info", paused: "warn", candidate: "neutral", rejected: "bad", replaced: "neutral", opted_out: "bad" };

function PersonRow({ v, panel, showActions = true }: { v: ContactView; panel: PanelContext; showActions?: boolean }) {
  const c = v.contact;
  const p = c.person;
  const ver = c.verification;
  const role = ROLE_LABEL[c.role];
  return (
    <li className="border-t border-[var(--border)] py-3 first:border-t-0 first:pt-0">
      <div className="flex flex-wrap items-baseline justify-between gap-2">
        <div>
          {c.outreach.order ? <span className="mr-1.5 text-[12px] text-[var(--muted)]">{c.outreach.order}.</span> : null}
          <span className="text-[14px] font-semibold">{p.name}</span>
          <span className="text-[13px] text-[var(--text-2)]"> · {p.title}</span>
        </div>
        <span className="flex flex-wrap gap-1.5">
          <Badge tone="accent" title={c.roleEvidence.join("\n")}>{`${role} · ${Math.round(c.roleConfidence * 100)}%`}</Badge>
          <Badge tone={STATUS_TONE[c.status]}>{c.status.replace("_", " ")}</Badge>
        </span>
      </div>
      <div className="mt-1.5 flex flex-wrap items-center gap-1.5">
        <Check ok={ver.employment ? ver.employment.ok : false} label="employment" title={ver.employment?.detail} />
        <Check ok={ver.email ? ver.email.ok : null} label="email" title={p.email} />
        <Check ok={ver.phone ? isPhoneVerified(p) && ver.phone.ok : null} label={ver.phone && isPhoneVerified(p) ? "phone verified" : "phone"} title={p.phone} />
        {p.verifiedBy === "synthetic" && <Badge tone="warn" title="Generated by the mock enrichment provider; never accepted in live mode">synthetic</Badge>}
        {ver.duplicateOf && <Badge tone="warn">duplicate</Badge>}
        {ver.suppressed && <Badge tone="bad">suppressed</Badge>}
        {ver.lastError && <Badge tone="warn" title={ver.lastError}>{`verification retry ${ver.attempts}`}</Badge>}
        <span className="text-[11.5px] text-[var(--muted)]">
          {c.outreach.touchesSent} touch{c.outreach.touchesSent === 1 ? "" : "es"}
          {c.outreach.lastTouchAt ? `, last ${fmtAgo(c.outreach.lastTouchAt)}` : ""}
          {c.engagement.score ? ` · engagement ${c.engagement.score}` : ""}
          {c.engagement.replied ? " · replied" : ""}
          {c.engagement.meeting ? " · meeting" : ""}
          {c.referredBy ? " · referred" : ""}
          {ver.checkedAt ? ` · checked ${fmtAgo(ver.checkedAt)}` : ""}
        </span>
      </div>
      <div className="mt-1.5 text-[12.5px] text-[var(--text-2)]">
        <span className="font-medium">Why this person: </span>
        {c.selectedReason ?? c.roleEvidence[0] ?? "candidate from account research"}
        {c.blockers.length > 0 && c.status !== "selected" && <span className="text-[var(--warn)]"> ({c.blockers[0]})</span>}
      </div>
      <div className="mt-2 flex flex-wrap items-center justify-between gap-2">
        <div className="text-[13px]">
          <span className="font-semibold">Next: </span>
          {v.nextAction}
        </div>
        {showActions && (
          <span className="flex flex-wrap items-center gap-1.5">
            {(c.status === "selected" || c.status === "paused") && <ConversationPanel ctx={{ ...panel, contact: p, contactId: c.id, contactRole: role.toLowerCase() }} label="Log conversation" small />}
            <ContactActions contactId={c.id} name={p.name} status={c.status} />
          </span>
        )}
      </div>
    </li>
  );
}

export function BuyingGroupCard({ view, panel }: { view: CoverageView; panel: PanelContext }) {
  const g = view.coverage;
  const plan = g?.plan;
  return (
    <Card id="contact" title={`4 · Contacts${g ? ` (${g.selectedCount} of ${plan?.targetSize})` : ""}`} hint={g?.summary} className="lg:col-span-2">
      <div className="mb-3 rounded-md bg-[var(--surface-2)] p-2.5 text-[13px]">
        <span className="font-semibold">Next for this account: </span>
        {view.nextAction}
      </div>
      {plan && (
        <details className="mb-3 text-[12.5px] text-[var(--text-2)]">
          <summary className="cursor-pointer">
            <span className="font-medium">Why this group: </span>
            {plan.roles.map((r) => ROLE_LABEL[r].toLowerCase()).join(" → ")}, staggered over {plan.stagger[plan.stagger.length - 1] ?? 0} days ({plan.source === "learned" ? `learned from history for ${plan.segment.replace(/\|\*/g, "").replace(/\|/g, " · ")}` : "default plan"})
          </summary>
          <ul className="mt-1 list-disc pl-5">
            {plan.evidence.map((e) => (
              <li key={e}>{e}</li>
            ))}
          </ul>
        </details>
      )}
      {view.group.length ? (
        <ul>
          {view.group.map((v) => (
            <PersonRow key={v.contact.id} v={v} panel={panel} />
          ))}
        </ul>
      ) : (
        <div className="text-[13px] text-[var(--muted)]">No one verified yet. The contact research team is mapping and verifying people at this account.</div>
      )}
      {g && g.gaps.length > 0 && (
        <div className="mt-3 rounded-md border border-dashed border-[var(--border-strong)] p-2.5 text-[12.5px]">
          <div className="font-semibold">Coverage gaps</div>
          <ul className="mt-1 list-disc pl-5 text-[var(--text-2)]">
            {g.gaps.map((x, i) => (
              <li key={`${x.role}-${i}`}>
                <span className="font-medium">{ROLE_LABEL[x.role]}</span>: {x.reason}
              </li>
            ))}
          </ul>
        </div>
      )}
      <div className="mt-3 flex flex-wrap items-center gap-2">
        <ResearchContactsButton slug={view.slug} />
      </div>
      {view.candidates.length > 0 && (
        <details className="mt-3 text-[13px]">
          <summary className="cursor-pointer text-[12.5px] text-[var(--muted)]">
            {view.candidates.length} other candidate{view.candidates.length === 1 ? "" : "s"} ({view.candidates.filter((v) => v.contact.ready).length} verified)
          </summary>
          <ul className="mt-2">
            {view.candidates.map((v) => (
              <PersonRow key={v.contact.id} v={v} panel={panel} />
            ))}
          </ul>
        </details>
      )}
      {view.history.length > 0 && (
        <details className="mt-2 text-[13px]">
          <summary className="cursor-pointer text-[12.5px] text-[var(--muted)]">
            {view.history.length} replaced, rejected or opted out (history kept)
          </summary>
          <ul className="mt-2">
            {view.history.map((v) => (
              <PersonRow key={v.contact.id} v={v} panel={panel} showActions={false} />
            ))}
          </ul>
        </details>
      )}
    </Card>
  );
}
